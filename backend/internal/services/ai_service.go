// AIService handles AI-powered operations like challenge generation.
type AIService struct {
	apiKey     string
	model      string
	httpClient *http.Client
}

// NewAIService creates a new AIService instance.
func NewAIService(apiKey, model string) *AIService {
	if model == "" {
		model = "gemini-1.5-flash"
	}
	return &AIService{
		apiKey: strings.TrimSpace(apiKey),
		model:  strings.TrimSpace(model),
		httpClient: &http.Client{
			Timeout: 25 * time.Second,
		},
	}
}

// isPlaceholderKey checks whether the configured API key is still a template placeholder.
func (s *AIService) isPlaceholderKey() bool {
	k := strings.ToUpper(s.apiKey)
	return k == "" ||
		strings.Contains(k, "YOUR_") ||
		strings.Contains(k, "PLACEHOLDER") ||
		strings.Contains(k, "INSERT_") ||
		strings.Contains(k, "HERE")
}

// rawAIChallenge represents a single challenge object generated by the AI model.
type rawAIChallenge struct {
	Slug        string  `json:"slug"`
	Title       string  `json:"title"`
	Description string  `json:"description"`
	IconName    string  `json:"icon_name"`
	Type        string  `json:"type"`
	Metric      string  `json:"metric"`
	TargetValue float64 `json:"target_value"`
	TargetUnit  string  `json:"target_unit"`
}

type rawAIChallengeResponse struct {
	Challenges []rawAIChallenge `json:"challenges"`
}

// BuildPrompt constructs the prompt by interpolating season metadata and catalogs.
func BuildPrompt(seasonName, startsAt, endsAt, activitiesCatalogJSON, previousChallengesJSON string) string {
	if activitiesCatalogJSON == "" {
		activitiesCatalogJSON = DefaultActivitiesCatalog
	}
	if previousChallengesJSON == "" {
		previousChallengesJSON = "[]"
	}

	p := PromptTemplate
	p = strings.ReplaceAll(p, "{{season_name}}", seasonName)
	p = strings.ReplaceAll(p, "{{starts_at}}", startsAt)
	p = strings.ReplaceAll(p, "{{ends_at}}", endsAt)
	p = strings.ReplaceAll(p, "{{activities_catalog_json}}", activitiesCatalogJSON)
	p = strings.ReplaceAll(p, "{{previous_challenges_json}}", previousChallengesJSON)
	return p
}

// GenerateSeasonalChallenges generates exactly 5 challenges for a season.
func (s *AIService) GenerateSeasonalChallenges(season *models.Season, previousChallengesJSON string) ([]models.Challenge, error) {
	if s.isPlaceholderKey() {
		log.Printf("[AIService] ℹ️ AI_API_KEY is using placeholder. Generating 5 curated seasonal challenges for \"%s\"", season.Name)
		return s.generateThemedChallenges(season)
	}

	challenges, err := s.callAI(season, previousChallengesJSON)
	if err != nil {
		log.Printf("[AIService] ⚠️ AI generation call failed: %v. Falling back to curated seasonal challenges.", err)
		return s.generateThemedChallenges(season)
	}

	return challenges, nil
}

// callAI executes the prompt against the AI provider.
func (s *AIService) callAI(season *models.Season, previousChallengesJSON string) ([]models.Challenge, error) {
	startsAt := season.StartsAt.Format("02/01/2006")
	endsAt := season.EndsAt.Format("02/01/2006")

	prompt := BuildPrompt(season.Name, startsAt, endsAt, DefaultActivitiesCatalog, previousChallengesJSON)

	var rawJSON string
	var err error

	if strings.HasPrefix(s.apiKey, "sk-") {
		rawJSON, err = s.callOpenAI(prompt)
	} else {
		rawJSON, err = s.callGemini(prompt)
	}
	if err != nil {
		return nil, err
	}

	return s.parseAndValidateChallenges(rawJSON, season)
}

// callGemini queries Google's Gemini API via HTTP POST with automatic fallback for model names.
func (s *AIService) callGemini(prompt string) (string, error) {
	primaryModel := s.model
	if primaryModel == "" {
		primaryModel = "gemini-1.5-flash"
	}

	rawText, statusCode, err := s.executeGeminiRequest(prompt, primaryModel)
	if err == nil {
		return rawText, nil
	}

	// If the specified model was not found (404), attempt fallback to standard gemini-1.5-flash
	if statusCode == 404 && primaryModel != "gemini-1.5-flash" {
		log.Printf("[AIService] Model %s not found (404). Retrying with gemini-1.5-flash...", primaryModel)
		fallbackText, _, fallbackErr := s.executeGeminiRequest(prompt, "gemini-1.5-flash")
		if fallbackErr == nil {
			return fallbackText, nil
		}
	}

	return "", err
}

func (s *AIService) executeGeminiRequest(prompt, model string) (string, int, error) {
	url := fmt.Sprintf("https://generativelanguage.googleapis.com/v1beta/models/%s:generateContent?key=%s", model, s.apiKey)

	reqBody := map[string]interface{}{
		"contents": []map[string]interface{}{
			{
				"parts": []map[string]interface{}{
					{"text": prompt},
				},
			},
		},
		"generationConfig": map[string]interface{}{
			"temperature":      0.4,
			"responseMimeType": "application/json",
		},
	}

	bodyBytes, err := json.Marshal(reqBody)
	if err != nil {
		return "", 0, fmt.Errorf("gemini marshal error: %w", err)
	}

	req, err := http.NewRequest("POST", url, bytes.NewBuffer(bodyBytes))
	if err != nil {
		return "", 0, fmt.Errorf("gemini request creation error: %w", err)
	}
	req.Header.Set("Content-Type", "application/json")

	resp, err := s.httpClient.Do(req)
	if err != nil {
		return "", 0, fmt.Errorf("gemini http call error: %w", err)
	}
	defer resp.Body.Close()

	respBytes, err := io.ReadAll(resp.Body)
	if err != nil {
		return "", resp.StatusCode, fmt.Errorf("gemini read response error: %w", err)
	}

	if resp.StatusCode < 200 || resp.StatusCode >= 300 {
		return "", resp.StatusCode, fmt.Errorf("gemini status %d: %s", resp.StatusCode, string(respBytes))
	}

	var geminiResp struct {
		Candidates []struct {
			Content struct {
				Parts []struct {
					Text string `json:"text"`
				} `json:"parts"`
			} `json:"content"`
		} `json:"candidates"`
	}

	if err := json.Unmarshal(respBytes, &geminiResp); err != nil {
		return "", resp.StatusCode, fmt.Errorf("gemini response unmarshal error: %w", err)
	}

	if len(geminiResp.Candidates) == 0 || len(geminiResp.Candidates[0].Content.Parts) == 0 {
		return "", resp.StatusCode, fmt.Errorf("gemini returned empty candidates")
	}

	return geminiResp.Candidates[0].Content.Parts[0].Text, resp.StatusCode, nil
}

// callOpenAI queries OpenAI Chat Completions API via HTTP POST.
func (s *AIService) callOpenAI(prompt string) (string, error) {
	url := "https://api.openai.com/v1/chat/completions"

	model := "gpt-4o-mini"
	if s.model != "" && s.model != "gemini-1.5-flash" && s.model != "gemini-3.1-flash-lite" {
		model = s.model
	}

	reqBody := map[string]interface{}{
		"model": model,
		"messages": []map[string]string{
			{
				"role":    "system",
				"content": "Você é um assistente de gamificação de saúde para CareGames+. Responda APENAS com JSON no formato solicitado.",
			},
			{
				"role":    "user",
				"content": prompt,
			},
		},
		"temperature": 0.4,
		"response_format": map[string]string{
			"type": "json_object",
		},
	}

	bodyBytes, err := json.Marshal(reqBody)
	if err != nil {
		return "", fmt.Errorf("openai marshal error: %w", err)
	}

	req, err := http.NewRequest("POST", url, bytes.NewBuffer(bodyBytes))
	if err != nil {
		return "", fmt.Errorf("openai request creation error: %w", err)
	}
	req.Header.Set("Content-Type", "application/json")
	req.Header.Set("Authorization", "Bearer "+s.apiKey)

	resp, err := s.httpClient.Do(req)
	if err != nil {
		return "", fmt.Errorf("openai http call error: %w", err)
	}
	defer resp.Body.Close()

	respBytes, err := io.ReadAll(resp.Body)
	if err != nil {
		return "", fmt.Errorf("openai read response error: %w", err)
	}

	if resp.StatusCode < 200 || resp.StatusCode >= 300 {
		return "", fmt.Errorf("openai returned status %d: %s", resp.StatusCode, string(respBytes))
	}

	var openAIResp struct {
		Choices []struct {
			Message struct {
				Content string `json:"content"`
			} `json:"message"`
		} `json:"choices"`
	}

	if err := json.Unmarshal(respBytes, &openAIResp); err != nil {
		return "", fmt.Errorf("openai response unmarshal error: %w", err)
	}

	if len(openAIResp.Choices) == 0 {
		return "", fmt.Errorf("openai returned no choices")
	}

	return openAIResp.Choices[0].Message.Content, nil
}

// parseAndValidateChallenges cleans raw AI response and builds models.Challenge slices.
func (s *AIService) parseAndValidateChallenges(rawJSON string, season *models.Season) ([]models.Challenge, error) {
	cleaned := strings.TrimSpace(rawJSON)
	cleaned = strings.TrimPrefix(cleaned, "```json")
	cleaned = strings.TrimPrefix(cleaned, "```")
	cleaned = strings.TrimSuffix(cleaned, "```")
	cleaned = strings.TrimSpace(cleaned)

	var items []rawAIChallenge

	// 1. Try parsing {"challenges": [...]}
	var respObj rawAIChallengeResponse
	if err := json.Unmarshal([]byte(cleaned), &respObj); err == nil && len(respObj.Challenges) > 0 {
		items = respObj.Challenges
	} else {
		// 2. Try parsing direct array [...]
		if errArr := json.Unmarshal([]byte(cleaned), &items); errArr != nil || len(items) == 0 {
			return nil, fmt.Errorf("failed to parse AI JSON: %w (raw: %s)", err, cleaned)
		}
	}

	validMetrics := map[string]bool{
		"steps":          true,
		"water_ml":       true,
		"meditation_min": true,
		"custom":         true,
	}

	var results []models.Challenge
	for i, item := range items {
		if i >= 5 {
			break
		}

		metric := strings.ToLower(strings.TrimSpace(item.Metric))
		if !validMetrics[metric] {
			metric = "custom"
		}

		targetVal := item.TargetValue
		if targetVal <= 0 {
			targetVal = 100
		}

		unit := strings.TrimSpace(item.TargetUnit)
		if unit == "" {
			switch metric {
			case "steps":
				unit = "passos"
			case "water_ml":
				unit = "ml"
			case "meditation_min":
				unit = "minutos"
			default:
				unit = "dias"
			}
		}

		rawSlug := sanitizeSlug(item.Slug)
		if rawSlug == "" {
			rawSlug = fmt.Sprintf("desafio-%d", i+1)
		}
		if len(rawSlug) > 60 {
			rawSlug = rawSlug[:60]
		}

		title := strings.TrimSpace(item.Title)
		if len(title) > 100 {
			title = title[:100]
		}
		if title == "" {
			title = fmt.Sprintf("Desafio %d", i+1)
		}

		desc := strings.TrimSpace(item.Description)
		if len(desc) > 600 {
			desc = desc[:600]
		}

		icon := item.IconName
		if icon == "" {
			switch metric {
			case "steps":
				icon = "directions-walk"
			case "water_ml":
				icon = "water-drop"
			case "meditation_min":
				icon = "self-improvement"
			default:
				icon = "emoji-events"
			}
		}

		points := calculatePointsReward(metric, targetVal, i)

		c := models.Challenge{
			Slug:         rawSlug,
			Title:        title,
			Description:  desc,
			IconName:     sql.NullString{String: icon, Valid: true},
			Type:         "seasonal",
			Metric:       metric,
			TargetValue:  targetVal,
			TargetUnit:   unit,
			PointsReward: points,
			IsActive:     true,
			IsFixed:      false,
			SeasonID:     sql.NullString{String: season.ID, Valid: season.ID != ""},
			CreatedAt:    time.Now(),
			UpdatedAt:    time.Now(),
		}

		results = append(results, c)
	}

	// If fewer than 5 were returned by AI, top off with curated fallback challenges
	if len(results) < 5 {
		fallbacks, _ := s.generateThemedChallenges(season)
		for _, fb := range fallbacks {
			if len(results) >= 5 {
				break
			}
			results = append(results, fb)
		}
	}

	return results, nil
}

// calculatePointsReward assigns appropriate seasonal reward points based on metric and target.
func calculatePointsReward(metric string, targetValue float64, index int) int {
	switch metric {
	case "steps":
		if targetValue >= 150000 {
			return 1500
		} else if targetValue >= 100000 {
			return 1200
		}
		return 1000
	case "water_ml":
		if targetValue >= 60000 {
			return 900
		}
		return 800
	case "meditation_min":
		if targetValue >= 250 {
			return 1100
		}
		return 900
	case "custom":
		if targetValue >= 20 {
			return 1500
		}
		return 1000
	default:
		rewards := []int{800, 1000, 1100, 1200, 1500}
		if index >= 0 && index < len(rewards) {
			return rewards[index]
		}
		return 1000
	}
}

